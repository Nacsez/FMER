"""Generate flash-resident Spectrum sound data from the reviewed included loadout."""
import json
from pathlib import Path
import companion_bank as bank
ROOT=Path(__file__).resolve().parents[1]
def build():
 value=json.loads((ROOT/'host/loadout_profiles.json').read_text(encoding='utf8'))
 selected=next(p for p in value['profiles'] if p['id']=='A');lines=[]
 for key in selected['sound_ids']:
  state=bank.decode_record(value['sounds'][key]['entry']['native'])
  data=state['vced'];controls=state['controls'][145:178]+[state['controls'][194]]
  lines.append(' {{'+','.join(map(str,data))+'},{'+','.join(map(str,controls))+'},{'+','.join(map(str,state['modulation_profiles']))+'}},')
 return '// Generated by tools/build_spectrum_defaults.py; original FMER / GPL-3.0-only.\n#pragma once\n#include <stdint.h>\nstruct fmer_spectrum_sound {uint8_t vced[155];uint16_t controls[34];uint8_t modulation[2];};\nstatic const fmer_spectrum_sound fmer_spectrum_defaults[64]={\n'+'\n'.join(lines)+'\n};\n'
if __name__=='__main__':(ROOT/'firmware/fm1/spectrum_defaults.hpp').write_text(build(),encoding='utf8')
